import{test,expect}from'@playwright/test';
for(const width of [390,1100])test(`titre hors cadre et badges à droite à ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:1600});
  await page.goto('/demo/');
  const card=page.locator('flowio-pool-card'),header=card.locator('.hero'),frame=card.locator('ha-card.fio-card'),status=header.locator('flowio-header-status');
  await expect(header.locator('h2')).toBeVisible();
  await expect(frame.locator('.hero')).toHaveCount(0);
  await expect(header).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
  await expect(header).toHaveCSS('background-image','none');
  await expect(header).toHaveCSS('border-bottom-width','0px');
  await expect(status.locator('[data-type=treatment]')).toBeVisible();
  await expect(status.locator('[data-type=alarms]')).toBeVisible();
  const h=(await header.boundingBox())!,f=(await frame.boundingBox())!,title=(await header.locator('.hero-copy').boundingBox())!,s=(await status.boundingBox())!;
  expect(h.y+h.height).toBeLessThanOrEqual(f.y+1);
  expect(s.x).toBeGreaterThanOrEqual(title.x+title.width-1);
  expect(Math.abs(s.x+s.width-h.x-h.width)).toBeLessThanOrEqual(1);
  expect(s.y).toBeLessThan(f.y);
  expect(await header.evaluate(el=>el.scrollWidth>el.clientWidth+1)).toBe(false);
  expect(await card.evaluate(el=>el.scrollWidth>el.clientWidth+1)).toBe(false);
  if(width===390)for(const label of await status.locator('.badge-label').all())await expect(label).toBeHidden();
  await page.evaluate(()=>{const d=(window as any).demo;d.config.title='Bassin extérieur';d.apply();});
  await expect(header.locator('h2')).toHaveText('Bassin extérieur');
});
